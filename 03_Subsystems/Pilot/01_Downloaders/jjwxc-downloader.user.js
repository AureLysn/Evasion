  function readToc() {
    const seen = new Map();
    document.querySelectorAll('a[href*="chapterid="]').forEach((a) => {
      const m = a.href.match(/[?&]chapterid=(\d+)/);
      if (!m || seen.has(m[1])) return;
      const id = m[1];
      const tr = a.closest('tr');
      let title = '';
      if (tr) {
        const tds = [...tr.querySelectorAll('td')].map((t) => t.textContent.trim());
        title = tds.filter((t) => t && t !== id && !/^Chapter/i.test(t)).slice(0, 1).join('');
      }
      seen.set(id, { id, label: a.textContent.trim() || ('Chapter ' + id), title });
    });
    const list = [...seen.values()].sort((a, b) => Number(a.id) - Number(b.id));
    if (!list.length && curChapter) list.push({ id: curChapter, label: 'Chapter ' + curChapter, title: '' });
    return list;
  }

  const htmlToText = (html) => html
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/g, ' ').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&')
    .replace(/\n{3,}/g, '\n\n')
    .trim();

  async function fetchChapter(id) {
    const url = `${location.origin}/onebook.php?novelid=${novelId}&chapterid=${id}`;
    const res = await fetch(url, { credentials: 'include' });
    if (!res.ok) throw new Error('HTTP ' + res.status);
    const html = new TextDecoder('gb18030').decode(await res.arrayBuffer());
    const doc = new DOMParser().parseFromString(html, 'text/html');

    const bodyEl = doc.querySelector('#paragraph_comment_content');
    const body = bodyEl ? htmlToText(bodyEl.innerHTML) : '';
    let problem = '';
    if (!body) {
      const hint = (doc.body && doc.body.innerText || '').replace(/\s+/g, ' ').trim().slice(0, 120);
      problem = 'không thấy thân chương (VIP, cần đăng nhập, hoặc trang đổi cấu trúc): ' + hint;
    }

    let note = '';
    const label = [...doc.querySelectorAll('span')].find((s) => s.textContent.trim() === '作者有话说');
    if (label) {
      const head = label.closest('.note_chapter_title');
      const box = head ? head.parentElement : label.parentElement;
      if (box) {
        const clone = box.cloneNode(true);
        clone.querySelectorAll('.note_chapter_title, script, style').forEach((e) => e.remove());
        note = htmlToText(clone.innerHTML);
      }
    }
    return { id, url, pageTitle: doc.title.trim(), body, note, problem };
  }

