  async function run(onlyCurrent) {
    if (job.running) return;
    toc = readToc();
    if (!toc.length) { say('Không thấy chương nào trên trang này.'); return; }
    let picks = toc;
    if (onlyCurrent && curChapter) {
      picks = toc.filter((c) => c.id === curChapter);
      if (!picks.length) picks = [{ id: curChapter, label: 'Chapter ' + curChapter, title: '' }];
    } else {
      const from = Math.max(1, parseInt(els.from.value, 10) || 1);
      const to = Math.min(toc.length, parseInt(els.to.value, 10) || toc.length);
      picks = toc.slice(from - 1, to);
    }
    if (!picks.length) { say('Khoảng chương trống.'); return; }

    job.running = true; job.stop = false; job.paused = false; sync(); setBar(0);
    const parts = [];
    let bad = 0, done = 0;
    for (const meta of picks) {
      while (job.paused && !job.stop) await sleep(300);
      if (job.stop) break;
      say(`${done + 1}/${picks.length} — ${meta.label}`);
      try {
        const ch = await fetchChapter(meta.id);
        if (ch.problem) { bad++; log(`! ${meta.label}: ${ch.problem}`); }
        else log(`ok ${meta.label}: ${ch.body.length} ký tự thân, ${ch.note.length} ký tự lời tác giả`);
        parts.push(render(ch, meta.label, meta.title));
      } catch (e) {
        bad++;
        log(`! ${meta.label}: ${e.message}`);
        parts.push(`===== CHAPTER ${meta.id} | ${meta.label} =====\n## BODY (TRỐNG) — lỗi tải: ${e.message}\n`);
      }
      done++; setBar(done / picks.length);
      if (done < picks.length && CFG.delay > 0) await sleep(CFG.delay);
    }
    if (parts.length) {
      const head = `# JJWXC novelid=${novelId}\n# lấy ngày ${new Date().toISOString()}\n# ${parts.length} chương, ${bad} chương lỗi/trống\n\n`;
      saveText(`jjwxc-${novelId}-${parts.length}ch.txt`, head + parts.join('\n'));
    }
    say(job.stop ? `Đã dừng — ${parts.length} chương đã lưu.` : `Xong: ${parts.length} chương${bad ? `, ${bad} lỗi/trống` : ''}.`);
    job.running = false; job.stop = false; job.paused = false; sync();
  }

